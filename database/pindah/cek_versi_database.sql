SELECT k.asal AS jalankan, k.tabel, k.kolom, 'kolom belum ada' AS masalah
FROM @kolom k LEFT JOIN @nama n ON n.baru = k.tabel
WHERE COL_LENGTH('dbo.' + k.tabel, k.kolom) IS NULL
  AND (n.lama IS NULL OR COL_LENGTH('dbo.' + n.lama, k.kolom) IS NULL)
UNION ALL
SELECT o.asal, o.nama, NULL, 'objek belum ada'
FROM @objek o
WHERE OBJECT_ID('dbo.' + o.nama) IS NULL
  AND NOT EXISTS (SELECT 1 FROM sys.indexes i WHERE i.name = o.nama)
UNION ALL
SELECT 'migrasi 016', n.lama, NULL, 'tabel masih nama lama'
FROM @nama n WHERE OBJECT_ID('dbo.' + n.lama, 'U') IS NOT NULL
ORDER BY 1, 2, 3;
